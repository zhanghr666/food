    /** 单位换算 / 规格口语 */
    private val SPEC_WORDS = listOf(
        "净含量", "规格", "克", "毫升", "千克", "升", "斤", "大", "小", "中", "装",
    )

    /** 每轮依据最新常用食品、位置和别名生成语法。 */
    fun build(
        extraLocations: List<String> = emptyList(),
        extraFoods: List<String> = emptyList(),
    ): String {
        val words = linkedSetOf<String>()

        // 食物名（多字词；单字词太易误触发，靠解析层兜底）+ 用户自定义常用食品
        words += com.example.foodmanager.ocr.OcrTextParser.foodKeywordNames(extraFoods)
        words += Categories.ALL
        words += NUMBERS
        words += UNIT_WORDS
        words += LOCATION_WORDS
        // 用户自定义位置也加入词表，语音说它就能识别
        words += extraLocations.filter { it.isNotBlank() }
        words += TIME_WORDS
        words += FUNCTION_WORDS
        words += SPEC_WORDS
        words += "[unk]"

        return words.filter { it.isNotBlank() }
            .joinToString(prefix = "[", postfix = "]", separator = ",") { word -> "\"" + word.flatMap { c -> when (c) { '"' -> "\\\"".toList(); '\\' -> "\\\\".toList(); else -> if (c.code < 32) " ".toList() else listOf(c) } }.joinToString("") + "\"" }
    }
}
